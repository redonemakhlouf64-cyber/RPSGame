def available_languages():
    return LANGUAGES


def t(lang: str, key: str, default: str | None = None) -> str:
    code = lang if lang in FULL else "en"
    table = FULL.get(code) or EN
    val = table.get(key)
    if val is None and code != "en":
        val = EN.get(key)
    if val is None:
        val = EN.get(key, default if default is not None else key)
    return val


def language_label(code: str) -> str:
    for entry in LANGUAGES:
        if entry[0] == code:
            return entry[1]
    return "English"
